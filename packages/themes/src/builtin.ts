/**
 * Built-in themes. Each is described by a compact palette and expanded into the full token
 * set by `paletteTheme`, so every theme gets consistent diff/state/bus/agent colors.
 */
import type { ThemeFile, Token } from "./schema.ts"

export interface Palette {
  name: string
  appearance: "dark" | "light"
  bg: string
  panel?: string
  element: string
  overlay?: string
  border: string
  borderActive: string
  borderSubtle?: string
  text: string
  muted: string
  subtle?: string
  primary: string
  secondary: string
  accent: string
  red: string
  green: string
  yellow: string
  blue: string
  cyan: string
  magenta: string
  orange: string
  diffAddBg?: string
  diffDelBg?: string
  selection?: string
  /** Override any token directly. */
  extra?: Partial<Record<Token, string>>
}

/** Blend two "#rrggbb" colors (t = 0 → a, 1 → b). */
export function mix(a: string, b: string, t: number): string {
  const pa = hexToRgb(a)
  const pb = hexToRgb(b)
  const c = pa.map((v, i) => Math.round(v + ((pb[i] as number) - v) * t))
  return `#${c.map((v) => v.toString(16).padStart(2, "0")).join("")}`
}

function hexToRgb(h: string): [number, number, number] {
  const s = h.replace("#", "")
  const full =
    s.length === 3
      ? s
          .split("")
          .map((c) => c + c)
          .join("")
      : s.slice(0, 6)
  return [Number.parseInt(full.slice(0, 2), 16), Number.parseInt(full.slice(2, 4), 16), Number.parseInt(full.slice(4, 6), 16)]
}

function channel(v: number): number {
  const c = v / 255
  return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
}

/** WCAG 2.x relative luminance of a "#rrggbb" color. */
export function relativeLuminance(hex: string): number {
  const [r, g, b] = hexToRgb(hex)
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)
}

/** WCAG 2.x contrast ratio between two "#rrggbb" colors (1–21). */
export function contrastRatio(a: string, b: string): number {
  const la = relativeLuminance(a)
  const lb = relativeLuminance(b)
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05)
}

/**
 * Nudge `fg` toward white (dark `bg`) or black (light `bg`) just enough to reach `min`
 * contrast against `bg`. Colors that already pass are returned unchanged.
 */
export function ensureContrast(fg: string, bg: string, min: number): string {
  if (contrastRatio(fg, bg) >= min) return fg
  const target = relativeLuminance(bg) < 0.18 ? "#ffffff" : "#000000"
  for (let t = 0.02; t < 1; t += 0.02) {
    const c = mix(fg, target, t)
    if (contrastRatio(c, bg) >= min) return c
  }
  return target
}

export function paletteTheme(p: Palette): ThemeFile {
  const dark = p.appearance === "dark"
  const addBg = p.diffAddBg ?? mix(p.bg, p.green, dark ? 0.32 : 0.22)
  const delBg = p.diffDelBg ?? mix(p.bg, p.red, dark ? 0.32 : 0.2)
  // Derived colors are kept readable; explicit palette colors are used as given.
  const diffAdded = ensureContrast(dark ? mix(p.text, p.green, 0.15) : mix(p.text, p.green, 0.6), addBg, 4.5)
  const diffRemoved = ensureContrast(dark ? mix(p.text, p.red, 0.15) : mix(p.text, p.red, 0.6), delBg, 4.5)
  const theme: Record<Token, string> = {
    primary: p.primary,
    secondary: p.secondary,
    accent: p.accent,
    error: p.red,
    warning: p.yellow,
    success: p.green,
    info: p.blue,
    text: p.text,
    textMuted: p.muted,
    textSubtle: p.subtle ?? ensureContrast(mix(p.muted, p.bg, 0.35), p.bg, 3),
    background: p.bg,
    backgroundPanel: p.panel ?? p.bg,
    backgroundElement: p.element,
    backgroundOverlay: p.overlay ?? p.element,
    border: p.border,
    borderActive: p.borderActive,
    borderSubtle: p.borderSubtle ?? mix(p.border, p.bg, 0.45),
    selection: p.selection ?? mix(p.bg, p.blue, 0.3),
    diffAdded,
    diffRemoved,
    diffContext: p.muted,
    diffAddedBg: addBg,
    diffRemovedBg: delBg,
    diffLineNumber: p.muted,
    diffAddedLineNumberBg: addBg,
    diffRemovedLineNumberBg: delBg,
    stateIdle: p.muted,
    stateBusy: p.orange,
    stateWaiting: p.yellow,
    stateError: p.red,
    stateDone: p.green,
    spinner: p.orange,
    statusBar: p.panel ?? p.bg,
    statusText: p.muted,
    busTime: p.muted,
    busFrom: p.orange,
    busTo: p.orange,
    busBody: p.text,
    mention: p.cyan,
    toolName: p.text,
    toolArgs: p.muted,
    thought: p.subtle ?? p.muted,
    agentClaude: p.orange,
    agentCodex: p.text,
    agentOpencode: p.yellow,
    agentGemini: p.blue,
    agentCursor: p.magenta,
    agentCopilot: p.cyan,
    agentAmp: p.red,
    agentGoose: p.green,
    agentQwen: p.magenta,
    agentKiro: p.secondary,
    agentDroid: p.cyan,
    agentCline: p.blue,
    agentDefault: p.accent,
    ...p.extra,
  }
  return { name: p.name, theme }
}

